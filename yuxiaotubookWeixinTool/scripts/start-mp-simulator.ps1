# WeChat DevTools simulator: HTTP LAN IP (no TLS cert; wx.request blocks 127.0.0.1)
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

Write-Host "=== YuXiaoTu MP - DevTools (simulator) ===" -ForegroundColor Cyan

& (Join-Path $PSScriptRoot "check-mp-api.ps1")
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$ip = (Get-NetIPAddress -AddressFamily IPv4 | Where-Object {
  $_.IPAddress -notlike '127.*' `
    -and $_.IPAddress -notlike '169.254.*' `
    -and $_.InterfaceAlias -notmatch 'Loopback|vEthernet|WSL|VMware|VirtualBox|Hyper-V'
} | Sort-Object @{
  Expression = {
    if ($_.IPAddress -like '192.168.*') { 0 }
    elseif ($_.IPAddress -like '10.*') { 1 }
    elseif ($_.IPAddress -match '^172\.(1[6-9]|2\d|3[01])\.') { 2 }
    else { 9 }
  }
} | Select-Object -First 1).IPAddress

if (-not $ip) {
  Write-Host "[FAIL] No WLAN/LAN IPv4. Connect Wi-Fi first." -ForegroundColor Red
  exit 1
}

& (Join-Path $PSScriptRoot "check-wechat-proxy.ps1")

$clash7890 = Get-NetTCPConnection -LocalPort 7890 -State Listen -ErrorAction SilentlyContinue
if ($clash7890) {
  $viaProxy = & curl.exe -k -x "http://127.0.0.1:7890" -s -o NUL -w "%{http_code}" "https://${ip}:8443/api/v1/site/config" 2>$null
  if ($viaProxy -ne "200") {
    Write-Host ""
    Write-Host "[BLOCK] Clash on 7890 breaks WeChat local API (-111). Before opening DevTools:" -ForegroundColor Red
    Write-Host "  -> WeChat: Settings -> Proxy -> NO PROXY, restart DevTools" -ForegroundColor Red
    Write-Host "  -> OR run: .\fix-mp-network.bat" -ForegroundColor Red
    Write-Host ""
  }
}

$envFile = Join-Path $PWD ".env.development"
$content = @"
# DevTools simulator (generated by start-mp-simulator.ps1)
# LAN HTTP: no self-signed cert; requires Details->Local Settings->skip domain check
VITE_API_BASE=http://${ip}:8000/api/v1
VITE_MEDIA_ORIGIN=http://${ip}:8000
VITE_TRADE_API_BASE=http://${ip}:8081/api/v1
"@
Set-Content -Path $envFile -Value $content -Encoding UTF8
Write-Host "Updated .env.development -> http://${ip}:8000 (HTTP, no cert)" -ForegroundColor Green

$httpOk = $false
try {
  $code = & curl.exe -s -o NUL -w "%{http_code}" "http://${ip}:8000/api/v1/site/config" 2>$null
  if ($code -eq "200") { $httpOk = $true }
} catch {}
if (-not $httpOk) {
  Write-Host "[FAIL] http://${ip}:8000 not reachable. Start local backend first." -ForegroundColor Red
  exit 1
}
Write-Host "[OK] http://${ip}:8000 reachable" -ForegroundColor Green

& (Join-Path $PSScriptRoot "build-mp-local.ps1")

Write-Host ""
Write-Host "=== WeChat DevTools checklist ===" -ForegroundColor Yellow
Write-Host "1. Settings -> Proxy -> NO PROXY"
Write-Host "2. Details -> Local Settings -> CHECK skip domain/TLS (已勾选)"
Write-Host "3. Clear cache -> recompile"
Write-Host "4. Console: http://${ip}:8000/api/v1  version 20260711-16+"
Write-Host ""
