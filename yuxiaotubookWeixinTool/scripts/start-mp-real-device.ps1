# Real device: LAN IP + HTTPS proxy + build
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

Write-Host "=== YuXiaoTu MP - Real device ===" -ForegroundColor Cyan

& (Join-Path $PSScriptRoot "check-mp-api.ps1")
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$ip = (Get-NetIPAddress -AddressFamily IPv4 | Where-Object {
  $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' -and
  $_.InterfaceAlias -notmatch 'Loopback|vEthernet|WSL|VMware|VirtualBox|Hyper-V'
} | Sort-Object @{
  Expression = { if ($_.IPAddress -like '192.168.*') { 0 } elseif ($_.IPAddress -like '10.*') { 1 } else { 9 } }
} | Select-Object -First 1).IPAddress

$envFile = Join-Path $PWD ".env.development"
$content = @"
# Real device (generated by start-mp-real-device.ps1)
VITE_API_BASE=https://${ip}:8443/api/v1
VITE_MEDIA_ORIGIN=https://${ip}:8443
VITE_TRADE_API_BASE=https://${ip}:8444/api/v1
"@
Set-Content -Path $envFile -Value $content -Encoding UTF8
Write-Host "Updated .env.development -> HTTPS $ip" -ForegroundColor Green

& (Join-Path $PSScriptRoot "build-mp-local.ps1")

Write-Host ""
Write-Host "=== Real device checklist ===" -ForegroundColor Yellow
Write-Host "1. Phone and PC on SAME WiFi (phone must NOT use mobile data)"
Write-Host "2. Run dev-https-proxy.bat in another window"
Write-Host "3. WeChat DevTools -> disable domain check + TLS check"
Write-Host "4. Use 'Real device debug' (not only preview QR) if cert errors persist"
Write-Host ""
Write-Host "If ERR_CERT_AUTHORITY_INVALID on phone:" -ForegroundColor Cyan
Write-Host "  A) PC simulator: .\start-mp-simulator.bat (easiest)"
Write-Host "  B) Install mkcert: .\setup-mkcert.bat -> restart proxy -> install rootCA.pem on Android"
Write-Host ""

& (Join-Path $PSScriptRoot "dev-https-proxy.ps1")
